/**
 * Attendance Constants
 */

const ATTENDANCE_STATUSES = Object.freeze({
    PRESENT: "PRESENT",
    ABSENT: "ABSENT",
    HALF_DAY: "HALF_DAY",
});

const VALID_ATTENDANCE_STATUSES = Object.freeze(Object.values(ATTENDANCE_STATUSES));

const REGULARIZATION_STATUSES = Object.freeze({
    PENDING: "PENDING",
    APPROVED: "APPROVED",
    REJECTED: "REJECTED",
    CANCELLED: "CANCELLED",
});

const VALID_REGULARIZATION_STATUSES = Object.freeze(Object.values(REGULARIZATION_STATUSES));

const VALID_REQUESTED_ATTENDANCE_STATUSES = Object.freeze([
    ATTENDANCE_STATUSES.PRESENT,
    ATTENDANCE_STATUSES.HALF_DAY,
]);

module.exports = {
    ATTENDANCE_STATUSES,
    VALID_ATTENDANCE_STATUSES,
    REGULARIZATION_STATUSES,
    VALID_REGULARIZATION_STATUSES,
    VALID_REQUESTED_ATTENDANCE_STATUSES,
};

